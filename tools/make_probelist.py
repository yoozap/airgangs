#!/usr/bin/env python3
"""Generate docs/probelist.txt — every C# probe paired with its counterpart.

The suite was being driven by a hand-written list passed on the command line,
which meant new probes were simply absent from it: 51 probe files existed on
disk and nothing guaranteed the suite ran them. This derives the list from what
is actually there, so a probe cannot be silently left out of the run.

Pairing is by name: Editor/Probes/FooBarProbe.cs <-> tools/_probe_foobar.mjs
(or .py). A probe with no counterpart is still listed, with an empty mate, and
run_probes.sh reports it SOLO rather than skipping it.

  tools/make_probelist.py            write docs/probelist.txt
  tools/make_probelist.py --check    exit 1 if it is out of date
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROBES = os.path.join(ROOT, "unity", "Assets", "Editor", "Probes")
TOOLS = os.path.join(ROOT, "tools")
OUT = os.path.join(ROOT, "docs", "probelist.txt")

# Probes that intentionally have no numeric counterpart, or whose comparison is
# a string check rather than a float diff.
MODE = {"UiProbe": "strings"}
# Aggregators that call other probes' Print() — running them as well as their
# children would double-run the children, so they are skipped here.
SKIP = {"DetailProbe"}


def mate_for(stem):
    for ext in (".mjs", ".py"):
        cand = os.path.join(TOOLS, f"_probe_{stem}{ext}")
        if os.path.exists(cand):
            runner = "node" if ext == ".mjs" else "python3"
            return f"{runner} tools/_probe_{stem}{ext}"
    return ""


rows = []
for name in sorted(os.listdir(PROBES)):
    if not name.endswith("Probe.cs"):
        continue
    cls = name[:-3]
    if cls in SKIP:
        continue
    src = open(os.path.join(PROBES, name), errors="replace").read()
    m = re.search(r"^namespace\s+([\w.]+)", src, re.M)
    ns = m.group(1) if m else "TbilisiFly.Probes"
    if not re.search(r"\bstatic\s+void\s+Run\s*\(", src):
        continue  # no entry point to -executeMethod
    stem = cls[:-5].lower()
    rows.append(f"{ns}.{cls}|{mate_for(stem)}|1e-5|{MODE.get(cls, '')}")

text = "# <class>|<counterpart command>|<tolerance>|<mode>\n" \
       "# Generated by tools/make_probelist.py — do not hand-edit.\n" + "\n".join(rows) + "\n"

if "--check" in sys.argv:
    cur = open(OUT).read() if os.path.exists(OUT) else ""
    if cur != text:
        print("docs/probelist.txt is out of date; run tools/make_probelist.py")
        raise SystemExit(1)
    print(f"probelist up to date ({len(rows)} probes)")
else:
    open(OUT, "w").write(text)
    paired = sum(1 for r in rows if r.split("|")[1])
    print(f"wrote {OUT}: {len(rows)} probes, {paired} with a counterpart, "
          f"{len(rows) - paired} standalone")
