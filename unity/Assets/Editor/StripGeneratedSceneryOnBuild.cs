using System.Collections.Generic;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace TbilisiFly.EditorTools
{
    /// <summary>
    /// STRIPS THE GENERATED SCENERY OUT OF A PLAYER BUILD'S COPY OF THE SCENE.
    ///
    /// Editor/BuildPlayableScene.cs already does this before SaveScene, with a
    /// long comment on why it is a CORRECTNESS fix and not only a size one:
    /// only ShopfrontRenderer's ClearChildren walks real Transform children,
    /// while ParkRenderer's and LandmarkRenderer's clear a private `_children`
    /// list that a fresh load leaves empty and MetroRenderer/MallRenderer/
    /// StreetFurnitureRenderer have no clear at all — so a deserialised copy
    /// SURVIVES and the OnEnable rebuild is added alongside it, ~964 scenery
    /// objects drawn twice, co-located.
    ///
    /// The on-disk Assets/Scenes/Game.unity is clean (grep finds no `grass_`).
    /// BuildPipeline.BuildPlayer puts it back: building a scene LOADS it, every
    /// [ExecuteAlways] renderer's OnEnable runs during that load, and the
    /// pipeline serialises the LOADED state. Measured on the first real player
    /// build: `strings level0 | grep -c '^grass_'` = 649, and the player's own
    /// log reported exactly double the editor's child counts —
    /// GRASS children=1340 vs 670, ROADS 30 vs 15, RIVER 4 vs 2,
    /// SHEDSCENEFILL 4 vs 2 — while every real count (chunks, cells, quads,
    /// segs, tris) matched to the unit.
    ///
    /// This runs at the one point that fixes it for every build: after the
    /// scene is loaded for processing and before it is written. It keys off the
    /// renderer COMPONENTS, which is the same set BuildPlayableScene's
    /// `sceneryRoots` holds — each of those is a dedicated GameObject whose
    /// only job is to carry one renderer. The baked city chunk/terrain objects
    /// (CombatBuildingChunk, the chunk_* meshes under "Buildings") are NOT
    /// children of any of them and are deliberately left alone: per-building HP
    /// and the carved blast holes index into those meshes' vertex ranges.
    ///
    /// Play mode is untouched — OnProcessScene also runs on entering play, and
    /// is skipped when there is no BuildReport.
    /// </summary>
    public sealed class StripGeneratedSceneryOnBuild : IProcessSceneWithReport
    {
        public int callbackOrder => 0;

        /// <summary>Every component whose OnEnable regenerates its children
        /// from the data pipeline on each load.</summary>
        static readonly System.Type[] RegeneratingRenderers =
        {
            typeof(TbilisiFly.City.CityRenderer),
            typeof(TbilisiFly.City.ShopfrontRenderer),
            typeof(TbilisiFly.City.VegetationRenderer),
            typeof(TbilisiFly.City.ParkRenderer),
            typeof(TbilisiFly.City.MetroRenderer),
            typeof(TbilisiFly.City.MallRenderer),
            typeof(TbilisiFly.City.StreetFurnitureRenderer),
            typeof(TbilisiFly.City.LandmarkRenderer),
            typeof(TbilisiFly.City.WindsockRenderer),
            typeof(TbilisiFly.City.RoadNetworkRenderer),
            typeof(TbilisiFly.City.RiverRenderer),
            typeof(TbilisiFly.City.GrassRenderer),
            typeof(TbilisiFly.Flight.ShedSceneFill),
            typeof(TbilisiFly.Props.WarehouseInteriorFill),
        };

        public void OnProcessScene(Scene scene, BuildReport report)
        {
            if (report == null) return; // entering play mode, not building

            var roots = new List<GameObject>();
            foreach (var root in scene.GetRootGameObjects())
                foreach (var t in RegeneratingRenderers)
                    foreach (var c in root.GetComponentsInChildren(t, true))
                        if (c is Component comp && !roots.Contains(comp.gameObject))
                            roots.Add(comp.gameObject);

            int strippedRoots = 0, strippedObjects = 0;
            foreach (var go in roots)
            {
                if (go == null) continue;
                strippedRoots++;
                for (int i = go.transform.childCount - 1; i >= 0; i--)
                {
                    var child = go.transform.GetChild(i).gameObject;
                    strippedObjects += child.GetComponentsInChildren<Transform>(true).Length;
                    Object.DestroyImmediate(child);
                }
            }
            Debug.Log($"PLAYERBUILD stripped_generated scene={scene.name} roots={strippedRoots} " +
                      $"objects={strippedObjects} (regenerated by each renderer's OnEnable on every load)");
        }
    }
}
